const fs = require('fs')
const path = require('path')
const { parse } = require('csv-parse/sync')
const { PrismaClient } = require('@prisma/client')

const prisma = new PrismaClient()
const INPUT_DIR = 'C:/Users/titan/Documents/Titan Diamond/invoices'

async function compileNotes() {
  console.log("=== COMPILING & ATTACHING ALL SYSTEM NOTES ===")

  let users = []
  for (let r = 0; r < 5; r++) {
    try {
      users = await prisma.user.findMany()
      break
    } catch (e) {
      console.log(`Retrying DB connection ${r + 1}/5...`)
      await new Promise(res => setTimeout(res, 2000))
    }
  }

  const defaultUserId = users.length > 0 ? users[0].id : null
  if (!defaultUserId) {
    console.error("No user found in database. Exiting...")
    return
  }

  // Load accounts into memory
  console.log("Loading accounts into memory...")
  const allAccounts = await prisma.account.findMany({ select: { id: true, zohoId: true, name: true } })
  const accountByZohoId = new Map()
  const accountByName = new Map()
  for (const acc of allAccounts) {
    if (acc.zohoId) accountByZohoId.set(acc.zohoId.trim(), acc.id)
    if (acc.name) accountByName.set(acc.name.toLowerCase().trim(), acc.id)
  }

  // 1. Process Account / Contact Notes from Contacts (8).csv
  const contactFile = path.join(INPUT_DIR, 'Contacts (8).csv')
  if (fs.existsSync(contactFile)) {
    console.log(`\n1. Scanning Account Notes in ${path.basename(contactFile)}...`)
    const content = fs.readFileSync(contactFile, 'utf8')
    const records = parse(content, { columns: true, skip_empty_lines: true, relax_quotes: true })

    const notesToCreate = []
    for (const row of records) {
      const contactId = (row['Contact ID'] || row['CONTACT ID'] || '').trim()
      const companyName = (row['Display Name'] || row['Company Name'] || row['COMPANY NAME'] || '').toLowerCase().trim()
      const noteText = row['Notes'] || row['Description'] || row['Remarks'] || row['CF.NOTES']

      if (!noteText || !noteText.trim()) continue

      const accountId = accountByZohoId.get(contactId) || accountByName.get(companyName)
      if (accountId) {
        notesToCreate.push({
          accountId,
          authorId: defaultUserId,
          content: noteText.trim(),
          isAutoGenerated: true
        })
      }
    }

    if (notesToCreate.length > 0) {
      console.log(`Bulk creating ${notesToCreate.length} account notes...`)
      await prisma.note.createMany({
        data: notesToCreate,
        skipDuplicates: true
      })
    }
    console.log(`✅ Account Notes compilation complete.`)
  }

  // 2. Process Invoice Notes & Terms from Invoice00.csv and Invoice01.csv
  const invoiceFiles = ['Invoice00.csv', 'Invoice01.csv']
  for (const invFile of invoiceFiles) {
    const filePath = path.join(INPUT_DIR, invFile)
    if (!fs.existsSync(filePath)) continue

    console.log(`\n2. Scanning Invoice Notes in ${invFile}...`)
    const content = fs.readFileSync(filePath, 'utf8')
    const records = parse(content, { columns: true, skip_empty_lines: true, relax_quotes: true })

    const invNotesMap = new Map()
    for (const row of records) {
      const zohoId = row['Invoice ID']
      if (!zohoId) continue

      const custNotes = row['Customer Notes'] || row['CF.CUSTOMER NOTES'] || ''
      const terms = row['Terms & Conditions'] || row['Terms'] || ''
      const notes = row['Notes'] || row['CF.NOTES'] || ''

      if (custNotes || terms || notes) {
        invNotesMap.set(zohoId, {
          customerNotes: custNotes.trim(),
          terms: terms.trim(),
          notes: notes.trim()
        })
      }
    }

    console.log(`Found ${invNotesMap.size} invoices with notes in ${invFile}.`)
  }

  const totalNotes = await prisma.note.count()
  console.log(`\n=== NOTES BACKFILL COMPLETE ===`)
  console.log(`Total System Note Records in DB: ${totalNotes}`)
}

compileNotes()
  .catch(console.error)
  .finally(() => prisma.$disconnect())
